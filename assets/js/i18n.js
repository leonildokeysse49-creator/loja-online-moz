function getCurrentLanguage() {
  const savedLanguage = localStorage.getItem("loja_mz_language");

  if (savedLanguage === "pt" || savedLanguage === "en") {
    return savedLanguage;
  }

  return window.APP_CONFIG?.defaultLanguage || "pt";
}

function getTranslation(key) {
  const language = getCurrentLanguage();

  return (
    translations[language]?.[key] ||
    translations.pt[key] ||
    key
  );
}

function applyTranslations() {
  const language = getCurrentLanguage();
  const dictionary = translations[language];

  document.documentElement.lang = language;

  const languageLabel = document.getElementById("current-language");

  if (languageLabel) {
    languageLabel.textContent = language.toUpperCase();
  }

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");

    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.getAttribute("data-i18n-placeholder");

    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    const key = element.getAttribute("data-i18n-title");

    if (dictionary[key]) {
      element.title = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    const key = element.getAttribute("data-i18n-aria-label");

    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });
}

function setLanguage(language) {
  if (!translations[language]) return;

  localStorage.setItem("loja_mz_language", language);
  applyTranslations();
  window.location.reload();
}
